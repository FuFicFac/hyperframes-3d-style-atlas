#!/usr/bin/env node
// build-gallery.mjs [--pilot <dir>] [--index references/style-index.json] [--with-neutral] [--no-sheet]
// Regenerates, from references/style-index.json (run build-index.mjs first):
//   <pilot>/gallery.html      one self-contained local page (inline CSS/JS/data, no network): a responsive grid of
//                             every demo MP4 (relative paths, muted, loop, preload="metadata", plays on hover / tap),
//                             with name, id, one-line description, demo topic and category filter buttons
//   <pilot>/contact-sheet.jpg 6 x N grid of one frame per style (at 60 % of each demo), labelled, ~3000 px wide
import { readFileSync, writeFileSync, existsSync, mkdtempSync, rmSync } from "node:fs";
import { dirname, join, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";

const SKILL = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = resolve(SKILL, "../..");
const args = process.argv.slice(2);
const flag = (k, d) => (args.includes(k) ? args[args.indexOf(k) + 1] : d);
const PILOT = resolve(flag("--pilot", join(ROOT, "Builder/HyperFrames/3d-style-atlas-pilot")));
const idx = JSON.parse(readFileSync(resolve(SKILL, flag("--index", "references/style-index.json")), "utf8"));
const items = idx.styles
  .filter((s) => args.includes("--with-neutral") || s.id !== "neutral")
  .map((s) => {
    const d = s.demos[0] ?? {};
    const mp4 = d.mp4 ? join(ROOT, d.mp4) : null;
    return { id: s.id, name: s.name, category: s.category, summary: s.summary, goodFor: s.goodFor, topic: d.topic ?? "", project: d.project ? d.project.split("/").pop() : "", src: mp4 && existsSync(mp4) ? relative(PILOT, mp4) : null, mb: d.mp4MB };
  })
  .sort((a, b) => a.project.localeCompare(b.project));

const POSTER_T = 9; // media-fragment start: the card shows a representative frame (~60 %) instead of an often-blank first frame
const esc = (x) => String(x ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const cats = [...new Set(items.map((i) => i.category))].sort();
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>3D Style Atlas</title>
<style>
  :root { --bg: #0d0e11; --panel: #16181d; --line: #262931; --text: #e9e7e2; --dim: #8d919a; --accent: #f2b544; }
  * { box-sizing: border-box; }
  body { margin: 0; background: var(--bg); color: var(--text); font: 15px/1.45 -apple-system, "Helvetica Neue", Helvetica, Arial, sans-serif; }
  header { padding: 28px 28px 8px; max-width: 1700px; margin: 0 auto; }
  h1 { margin: 0 0 4px; font-size: 26px; font-weight: 650; letter-spacing: .01em; }
  .sub { color: var(--dim); margin: 0 0 18px; }
  .filters { display: flex; flex-wrap: wrap; gap: 8px; }
  .filters button { background: var(--panel); color: var(--text); border: 1px solid var(--line); border-radius: 999px; padding: 6px 13px; font: inherit; font-size: 13px; cursor: pointer; }
  .filters button.on { background: var(--accent); color: #111; border-color: var(--accent); }
  main { display: grid; gap: 18px; padding: 18px 28px 40px; max-width: 1700px; margin: 0 auto; grid-template-columns: repeat(auto-fill, minmax(min(100%, 380px), 1fr)); }
  .card { background: var(--panel); border: 1px solid var(--line); border-radius: 12px; overflow: hidden; display: flex; flex-direction: column; }
  .card.hide { display: none; }
  .vid { position: relative; aspect-ratio: 16 / 9; background: #000; cursor: pointer; }
  .vid video { width: 100%; height: 100%; display: block; object-fit: cover; }
  .vid .badge { position: absolute; right: 8px; bottom: 8px; background: #000a; color: var(--dim); font-size: 11px; padding: 2px 7px; border-radius: 6px; pointer-events: none; }
  .vid .missing { position: absolute; inset: 0; display: grid; place-items: center; color: var(--dim); }
  .meta { padding: 12px 14px 14px; }
  .row { display: flex; justify-content: space-between; align-items: baseline; gap: 10px; }
  .name { font-weight: 650; font-size: 16px; }
  .id { color: var(--dim); font: 12px/1 Menlo, monospace; }
  .cat { color: var(--accent); font-size: 12px; margin: 3px 0 6px; }
  .desc { margin: 0 0 6px; }
  .topic { color: var(--dim); font-size: 13px; margin: 0; }
  footer { color: var(--dim); text-align: center; padding: 0 0 30px; font-size: 12px; }
</style>
</head>
<body>
<header>
  <h1>3D Style Atlas</h1>
  <p class="sub">${items.length} styles · hover or tap a video to play · generated by Skills/3d-style-atlas/scripts/build-gallery.mjs</p>
  <nav class="filters" id="filters"><button class="on" data-cat="all">All (${items.length})</button>${cats.map((c) => `<button data-cat="${esc(c)}">${esc(c)} (${items.filter((i) => i.category === c).length})</button>`).join("")}</nav>
</header>
<main id="grid">
${items.map((i) => `  <article class="card" data-cat="${esc(i.category)}">
    <div class="vid">${i.src ? `<video src="${esc(i.src)}#t=${POSTER_T}" muted loop playsinline preload="metadata"></video><span class="badge">${esc(i.project)}${i.mb ? ` · ${i.mb} MB` : ""}</span>` : `<div class="missing">no render yet</div>`}</div>
    <div class="meta">
      <div class="row"><span class="name">${esc(i.name)}</span><span class="id">${esc(i.id)}</span></div>
      <div class="cat">${esc(i.category)}</div>
      <p class="desc">${esc(i.summary)}</p>
      <p class="topic">Demo: ${esc(i.topic)}</p>
    </div>
  </article>`).join("\n")}
</main>
<footer>Paths are relative to this file. Regenerate after new renders: node build-index.mjs &amp;&amp; node build-gallery.mjs</footer>
<script>
  const cards = [...document.querySelectorAll(".card")];
  document.getElementById("filters").addEventListener("click", (e) => {
    const b = e.target.closest("button"); if (!b) return;
    document.querySelectorAll("#filters button").forEach((x) => x.classList.toggle("on", x === b));
    const c = b.dataset.cat;
    cards.forEach((card) => card.classList.toggle("hide", c !== "all" && card.dataset.cat !== c));
  });
  for (const card of cards) {
    const v = card.querySelector("video"); if (!v) continue;
    const box = card.querySelector(".vid");
    box.addEventListener("mouseenter", () => v.play().catch(() => {}));
    box.addEventListener("mouseleave", () => { v.pause(); });
    box.addEventListener("click", () => (v.paused ? v.play().catch(() => {}) : v.pause()));
  }
</script>
</body>
</html>
`;
writeFileSync(join(PILOT, "gallery.html"), html);
console.log(`build-gallery: ${join(PILOT, "gallery.html")} (${items.length} styles, ${items.filter((i) => !i.src).length} without MP4)`);

if (!args.includes("--no-sheet")) {
  const tmp = mkdtempSync(join(tmpdir(), "atlas-sheet-"));
  const W = 500, H = 281, cols = 6;
  const font = ["/System/Library/Fonts/Helvetica.ttc", "/System/Library/Fonts/Supplemental/Arial.ttf"].find(existsSync);
  const tiles = [];
  items.forEach((i, k) => {
    if (!i.src) return;
    const mp4 = join(PILOT, i.src);
    const dur = Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", mp4], { encoding: "utf8" }).trim()) || 10;
    const out = join(tmp, `tile_${String(k).padStart(2, "0")}.png`);
    const label = i.name.replace(/[:'\\]/g, " ");
    const draw = font ? `,drawbox=x=0:y=ih-34:w=iw:h=34:color=black@0.62:t=fill,drawtext=fontfile=${font}:text='${label}':x=10:y=h-26:fontsize=19:fontcolor=white` : "";
    execFileSync("ffmpeg", ["-v", "error", "-y", "-ss", (dur * 0.6).toFixed(2), "-i", mp4, "-frames:v", "1", "-vf", `scale=${W}:${H}${draw}`, out]);
    tiles.push(out);
  });
  const rows = Math.ceil(tiles.length / cols);
  const inputs = tiles.flatMap((t) => ["-i", t]);
  const layout = tiles.map((_, k) => `${(k % cols) * W}_${Math.floor(k / cols) * H}`).join("|");
  const sheet = join(PILOT, "contact-sheet.jpg");
  execFileSync("ffmpeg", ["-v", "error", "-y", ...inputs, "-filter_complex", `xstack=inputs=${tiles.length}:layout=${layout}:fill=black`, "-q:v", "3", sheet]);
  rmSync(tmp, { recursive: true, force: true });
  console.log(`build-gallery: ${sheet} (${cols}x${rows}, ${cols * W}x${rows * H})`);
}
