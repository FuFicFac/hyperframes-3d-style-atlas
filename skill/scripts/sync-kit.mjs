#!/usr/bin/env node
// sync-kit.mjs <projectDir> — copy kit/, styles/, vendor/ into <projectDir>/_atlas/ so the HyperFrames
// project is self-contained (HyperFrames serves only the project directory; ../ imports outside it
// are not reliable). Re-run after editing the kit or a style. Idempotent; removes stale files.
import { cpSync, rmSync, mkdirSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SKILL = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const proj = resolve(process.argv[2] ?? ".");
if (!existsSync(join(proj, "index.html"))) {
  console.error(`sync-kit: ${proj} has no index.html — pass a HyperFrames project directory`);
  process.exit(1);
}
const dest = join(proj, "_atlas");
rmSync(dest, { recursive: true, force: true });
mkdirSync(dest, { recursive: true });
for (const d of ["kit", "styles", "vendor"]) cpSync(join(SKILL, d), join(dest, d), { recursive: true });
// Dropbox can leave "<name> (... conflicted copy ...)" files when it races the delete+copy above: drop them
const prune = (d) => { for (const n of readdirSync(d, { withFileTypes: true })) { const f = join(d, n.name); if (n.name.includes("conflicted copy")) rmSync(f, { recursive: true, force: true }); else if (n.isDirectory()) prune(f); } };
prune(dest);
writeFileSync(join(dest, "package.json"), JSON.stringify({ type: "module", private: true }, null, 2) + "\n");
writeFileSync(join(dest, "README.md"), "Generated by 3d-style-atlas/scripts/sync-kit.mjs — do not edit here; edit Skills/3d-style-atlas and re-sync.\n");
if (!existsSync(join(proj, "package.json"))) writeFileSync(join(proj, "package.json"), JSON.stringify({ type: "module", private: true }, null, 2) + "\n");
console.log(`sync-kit: ${SKILL} -> ${dest}`);
