/**
 * layoutStrokeText(text, cap, { letterSpacing = .25, wordSpacing = .52, lineHeight = 1.55, align = "center",
 *                               bendRadius = .09, font = STROKE_FONT })
 *   -> { chars: [{ ch, i, x0, x1, line, strokes }], width, lines }
 *   Element-local metres. x is centred per line (align), the baseline of line 0 is y = 0, lines go down.
 *   Spacing/bend values are multiples of `cap`. strokes = expanded + filleted [x,y,0] point lists per glyph
 *   stroke (feed them to paths.sweepGeometry / tubeAlong). Unknown glyphs advance as a space.
 */
export function layoutStrokeText(text, cap, o = {}) {
  const font = (o.font ?? STROKE_FONT).glyphs;
  const spacing = (o.letterSpacing ?? 0.25) * cap, space = (o.wordSpacing ?? 0.52) * cap;
  const lineH = (o.lineHeight ?? 1.55) * cap, align = o.align ?? "center";
  const bend = (o.bendRadius ?? 0.09) * cap;
  const out = [];
  const lines = String(text).toUpperCase().split("\n");
  let i = 0, maxW = 0;
  lines.forEach((line, li) => {
    let x = 0;
    const row = [];
    for (const ch of line) {
      const g = font[ch];
      if (!g) { x += space; i++; continue; }
      const strokes = g.s.map((s) => filletPath(expandStroke(s, cap, [x, -li * lineH]), bend));
      row.push({ ch, i, x0: x, x1: x + g.w * cap, line: li, strokes });
      x += g.w * cap + spacing;
      i++;
    }
    const w = row.length ? row[row.length - 1].x1 : 0;
    const shift = align === "left" ? 0 : align === "right" ? -w : -w / 2;
    for (const c of row) {
      c.x0 += shift; c.x1 += shift;
      c.strokes = c.strokes.map((s) => s.map((p) => [p[0] + shift, p[1], p[2]]));
    }
    maxW = Math.max(maxW, w);
    out.push(...row);
    i++; // newline
  });
  return { chars: out, width: maxW, lines: lines.length };
}
