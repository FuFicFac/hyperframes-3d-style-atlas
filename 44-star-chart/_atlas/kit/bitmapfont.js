export const FONT_W = 5, FONT_H = 7;


/** measureBitmapText(str, { spacing = 1, lineGap = 3 }) -> { width, height, lines } in cells. */
export function measureBitmapText(str, { spacing = 1, lineGap = 3 } = {}) {
  const lines = String(str).toUpperCase().split("\n");
  const width = Math.max(...lines.map((l) => (l.length ? l.length * (FONT_W + spacing) - spacing : 0)));
  return { width, height: lines.length * FONT_H + (lines.length - 1) * lineGap, lines };
}

/**
 * bitmapTextCells(str, { spacing = 1, lineGap = 3, align = "left"|"center"|"right" }) -> [{ x, y, ch, ci, line, col }]
 * Filled cells, y up: y = 0 is the bottom row of the last line. Same layout as the voxel style's textVoxels.
 */
export function bitmapTextCells(str, o = {}) {
  const { spacing = 1, lineGap = 3, align = "left" } = o;
  const { width, lines } = measureBitmapText(str, { spacing, lineGap });
  const out = [];
  let ci = 0;
  lines.forEach((line, li) => {
    const lw = line.length ? line.length * (FONT_W + spacing) - spacing : 0;
    const x0 = align === "center" ? -Math.floor(lw / 2) : align === "right" ? width - lw : 0;
    const yTop = (lines.length - 1 - li) * (FONT_H + lineGap) + FONT_H - 1;
    [...line].forEach((ch, k) => {
      const g = FONT_5X7[ch] ?? FONT_5X7["?"];
      for (let r = 0; r < FONT_H; r++) for (let x = 0; x < FONT_W; x++) if (g[r][x] === "#") out.push({ x: x0 + k * (FONT_W + spacing) + x, y: yTop - r, ch, ci, line: li, col: k });
      ci++;
    });
    ci++;
  });
  return out;
}

